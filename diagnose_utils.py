def col_vals(table: pa.Table, name: str) -> list:
    """Безопасно извлекает список значений колонки из pyarrow.Table (или [] при отсутствии)."""
    if not name or name not in table.column_names:
        return []
    return table[name].to_pylist()


def sub(arr: list, idxs: list[int]) -> list:
    """Возвращает ненулевые (not None) элементы списка по заданным индексам."""
    if not arr or not idxs:
        return []
    n = len(arr)
    return [arr[i] for i in idxs if 0 <= i < n and arr[i] is not None]


def format_duration(seconds: float) -> str:
    """Форматирует длительность в секундах в строку вида '1 ч 12 мин 05 с' или '14 мин 20 с'."""
    total_sec = max(0, int(round(seconds)))
    hrs, rem = divmod(total_sec, 3600)
    mins, secs = divmod(rem, 60)
    if hrs > 0:
        return f"{hrs} ч {mins:02d} мин {secs:02d} с"
    if mins > 0:
        return f"{mins} мин {secs:02d} с"
    return f"{secs} с"


