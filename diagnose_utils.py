def col_vals(table: pa.Table, col_name: str) -> list:
    """Безопасно извлекает колонку из PyArrow Table в виде списка Python."""
    if not col_name or col_name not in table.column_names:
        return []
    return table[col_name].to_pylist()


def sub(vals: list, indices: list[int]) -> list[float]:
    """Выбирает непустые числовые значения по заданным индексам."""
    if not vals or not indices:
        return []
    out: list[float] = []
    n = len(vals)
    for i in indices:
        if 0 <= i < n:
            v = vals[i]
            if v is not None:
                try:
                    fv = float(v)
                    if fv == fv:
                        out.append(fv)
                except (TypeError, ValueError):
                    pass
    return out


def safe_median(vals: list[float], default: float | None = None) -> float | None:
    """Возвращает медиану непустого списка или значение по умолчанию."""
    return statistics.median(vals) if vals else default


def safe_mean(vals: list[float], default: float | None = None) -> float | None:
    """Возвращает среднее арифметическое непустого списка или значение по умолчанию."""
    return statistics.mean(vals) if vals else default


def format_duration(seconds: float) -> str:
    """Форматирует длительность в секундах в человекочитаемую строку."""
    if seconds is None or seconds < 0:
        return "0 с"
    total = int(round(seconds))
    if total < 60:
        return f"{total} с"
    mins, secs = divmod(total, 60)
    if mins < 60:
        return f"{mins} мин {secs:02d} с"
    hours, mins = divmod(mins, 60)
    return f"{hours} ч {mins:02d} мин"


def fmt_sec(seconds: float) -> str:
    """Короткий формат отметки времени в логе (секунды и мм:сс)."""
    if seconds is None:
        return "?"
    s = max(0.0, float(seconds))
    m, rem = divmod(int(s), 60)
    if m == 0:
        return f"{s:.1f}с"
    return f"{s:.0f}с ({m}:{rem:02d})"


def make_card(
    title: str,
    val: str,
    norm: str,
    status: str = "status-ok",
    badge: str | None = None,
    tooltip: str = "",
) -> dict:
    """Формирует словарь карточки для render_summary_html."""
    st = status if str(status).startswith("status-") else f"status-{status}"
    if badge is None:
        badge_map = {
            "status-ok": "НОРМА",
            "status-warn": "ВНИМАНИЕ",
            "status-bad": "ПРОБЛЕМА",
            "status-na": "НЕТ ДАННЫХ",
        }
        badge = badge_map.get(st, "ИНФО")
    return {
        "title": title,
        "badge": badge,
        "val": val,
        "norm": norm,
        "status": st,
        "tooltip": tooltip,
    }
